def launch_gazepoint_qc_dashboard(data=None, **kwargs):
    """Create a lightweight Shiny-for-Python QC app when the optional dependency exists."""
    try:
        from shiny import App, render, ui
    except Exception as exc:
        return {
            "status": "optional-backend-unavailable",
            "backend": "shiny",
            "error": str(exc),
            "hint": "Install gp3tools[dashboard]",
        }
    df = ensure_dataframe(data) if data is not None else pd.DataFrame()
    app_ui = ui.page_fluid(ui.h2("gp3tools QC dashboard"), ui.output_text_verbatim("summary"))

    def server(input, output, session):
        @output
        @render.text
        def summary():
            return f"Rows: {len(df):,}\nColumns: {df.shape[1]}\nMissing cells: {int(df.isna().sum().sum()):,}"

    return App(app_ui, server)


