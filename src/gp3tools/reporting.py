def export_gazepoint_tables(
    tables, output_dir, prefix="gazepoint", index=False, **kwargs
) -> dict[str, str]:
    root = Path(output_dir)
    root.mkdir(parents=True, exist_ok=True)
    out = {}
    items = tables.items() if isinstance(tables, dict) else [("table", tables)]
    for name, obj in items:
        if isinstance(obj, pd.DataFrame):
            path = root / f"{prefix}_{name}.csv"
            obj.to_csv(path, index=index)
            out[name] = str(path)
    return out


def export_gazepoint_model_tables(models, output_dir, prefix="model", **kwargs):
    from .stats import tidy_gazepoint_model_summary

    models = models if isinstance(models, dict) else {"model": models}
    tables = {name: tidy_gazepoint_model_summary(model) for name, model in models.items()}
    return export_gazepoint_tables(tables, output_dir, prefix=prefix, **kwargs)


def write_gazepoint_outputs(results, output_dir, prefix="gazepoint", **kwargs):
    root = Path(output_dir)
    root.mkdir(parents=True, exist_ok=True)
    written = {}
    if isinstance(results, pd.DataFrame):
        results = {"result": results}
    if isinstance(results, dict):
        for k, v in results.items():
            if isinstance(v, pd.DataFrame):
                p = root / f"{prefix}_{k}.csv"
                v.to_csv(p, index=False)
                written[k] = str(p)
            elif isinstance(v, (dict, list, tuple, str, int, float, bool)):
                try:
                    p = root / f"{prefix}_{k}.json"
                    p.write_text(json.dumps(v, indent=2, default=str), encoding="utf-8")
                    written[k] = str(p)
                except Exception:
                    pass
    return written


