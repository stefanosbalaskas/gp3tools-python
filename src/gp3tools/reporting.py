def save_gazepoint_plots(plots, output_dir, prefix="plot", dpi=150, **kwargs):
    root = Path(output_dir)
    root.mkdir(parents=True, exist_ok=True)
    out = {}
    plots = plots if isinstance(plots, dict) else {"plot": plots}
